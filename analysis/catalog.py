"""Generate the reader catalog from separately identified lab and reference sources."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def load_catalog():
    area=ROOT/'analysis/m1/catalog'
    lab=json.loads((area/'lab-target.json').read_text())
    # Prefer the study fragment for the same HGVS; preserve the genomic source JSON.
    rows=[lab,*[row for row in json.loads((area/'variants.json').read_text()) if row['hgvs']!=lab['hgvs']]]
    if len({r['id'] for r in rows})!=len(rows):raise ValueError('Catalog IDs must be unique.')
    for row in rows:
        if row['wt'][row['position']-1]!=row['ref'] or row['ref']==row['alt']:raise ValueError('Catalog variant does not match WT.')
    return rows

def render_catalog():
    return "'use strict';\n// Generated by python -m analysis.catalog --write; do not edit this file manually.\nconst VARIANT_CATALOG = "+json.dumps(load_catalog(),indent=2,ensure_ascii=False)+";\nif(typeof module!=='undefined') module.exports=VARIANT_CATALOG;\n"

def main():
    parser=argparse.ArgumentParser(description=__doc__);group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write',action='store_true');group.add_argument('--check',action='store_true');args=parser.parse_args()
    dest=ROOT/'m0-dashboard/variant-catalog.js';text=render_catalog()
    if args.write:dest.write_text(text)
    elif dest.read_text()!=text:parser.exit(1,'Generated catalog differs; run --write.\n')
if __name__=='__main__':main()
